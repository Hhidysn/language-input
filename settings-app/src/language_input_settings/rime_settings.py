def _dir_size(path: Path) -> int:
    total = 0
    if not path.is_dir():
        return 0
    try:
        for entry in path.rglob("*"):
            try:
                if entry.is_file():
                    total += entry.stat().st_size
            except OSError:
                continue
    except OSError:
        return total
    return total


def _custom_has_enable_override(path: Path) -> bool:
    if not path.is_file():
        return False
    try:
        document = _load_yaml(path)
    except RimeSettingsError:
        return False
    patch = document.get("patch") if isinstance(document, dict) else None
    return isinstance(patch, dict) and "translator/enable_user_dict" in patch


def learning_state(
    user_dir: str | os.PathLike[str] | None = None,
) -> dict[str, Any]:
    """User-dictionary presence/size + effective ``translator/enable_user_dict``.

    The effective value is read from the compiled schema; when the key is absent
    librime's default is ``true`` (so an absent key means learning is enabled).
    """
    resolved = _coerce_user_dir(user_dir)
    userdb = _userdb_path(user_dir)
    present = userdb.is_dir()
    schemas: dict[str, dict[str, Any]] = {}
    enabled_flags: list[bool] = []
    for schema_id in LANGUAGE_SCHEMAS:
        document = _load_yaml(_compiled_schema_path(schema_id, user_dir))
        translator = document.get("translator") if isinstance(document, dict) else None
        if isinstance(translator, dict) and "enable_user_dict" in translator:
            explicit = True
            value = bool(translator.get("enable_user_dict"))
        else:
            # Rime's built-in default is true; an absent key means enabled.
            explicit = False
            value = True
        custom = _custom_schema_path(schema_id, user_dir)
        schemas[schema_id] = {
            "enable_user_dict": value,
            "explicit": explicit,
            "custom_path": str(custom),
            "custom_exists": custom.is_file(),
            "custom_has_override": _custom_has_enable_override(custom),
        }
        enabled_flags.append(value)
    return {
        "user_dir": str(resolved),
        "userdb_path": str(userdb),
        "userdb_present": present,
        "userdb_size": _dir_size(userdb) if present else 0,
        "schemas": schemas,
        "enabled": all(enabled_flags) if enabled_flags else True,
    }


# -- app-owned <schema>.custom.yaml patching ---------------------------------

def _load_rt(path: Path):
    yaml = _require_yaml()
    try:
        document = yaml().load(path.read_text(encoding="utf-8-sig"))
    except Exception as exc:  # noqa: BLE001 - malformed user file
        raise RimeSettingsError(f"cannot parse existing {path}: {exc}") from exc
    if document is None:
        document = _require_map()()
    if not isinstance(document, dict):
        raise RimeSettingsError(f"{path} is not a YAML mapping")
    return document


def _dump_rt(path: Path, document) -> None:
    yaml = _require_yaml()()
    yaml.default_flow_style = False
    yaml.allow_unicode = True
    yaml.preserve_quotes = True
    yaml.indent(mapping=2, sequence=4, offset=2)
    from io import StringIO

    buffer = StringIO()
    yaml.dump(document, buffer)
    yaml_io.atomic_write_text(path, buffer.getvalue())


def _custom_meaningful(document) -> bool:
    for key, value in document.items():
        if key == "patch":
            if value:
                return True
            continue
        return True
    return False


def _write_custom_patch_key(path: Path, key: str, value: Any) -> bool:
    if path.is_file():
        document = _load_rt(path)
    else:
        map_class = _require_map()
        document = map_class()
        document["patch"] = map_class()
        setter = getattr(document, "yaml_set_start_comment", None)
        if callable(setter):
            setter(_HEADER_COMMENT)
    patch = document.get("patch")
    if not isinstance(patch, dict):
        patch = _require_map()()
        document["patch"] = patch
    if patch.get(key, _MISSING) == value:
        return False
    yaml_io.backup_file(path)
    patch[key] = value
    _dump_rt(path, document)
    return True


def _remove_custom_patch_key(path: Path, key: str) -> tuple[bool, bool]:
    """Remove ``key`` from the patch; delete the file if nothing remains.

    Returns ``(removed, deleted)``.
    """
    if not path.is_file():
        return False, False
    document = _load_rt(path)
    patch = document.get("patch")
    if not isinstance(patch, dict) or key not in patch:
        return False, False
    del patch[key]
    yaml_io.backup_file(path)
    if _custom_meaningful(document):
        _dump_rt(path, document)
        return True, False
    try:
        path.unlink()
    except OSError as exc:  # pragma: no cover - defensive
        raise RimeSettingsError(f"cannot remove {path}: {exc}") from exc
    return True, True


def set_learning(
    on: bool,
    *,
    deploy: bool = True,
    user_dir: str | os.PathLike[str] | None = None,
) -> dict[str, Any]:
    """Toggle ``translator/enable_user_dict`` for both Language Input schemas.

    ``off`` writes ``enable_user_dict: false`` (which also stops *using*
    already-learned words, design doc §8).  ``on`` removes our override so the
    built-in default (true) applies again -- this restores the original files
    (and deletes a custom file that we created and is now empty).
    """
    schemas: dict[str, dict[str, Any]] = {}
    for schema_id in LANGUAGE_SCHEMAS:
        custom = _custom_schema_path(schema_id, user_dir)
        if on:
            removed, deleted = _remove_custom_patch_key(custom, "translator/enable_user_dict")
            schemas[schema_id] = {
                "action": "enable",
                "removed_override": removed,
                "custom_deleted": deleted,
                "custom_path": str(custom),
                "custom_exists": custom.is_file(),
            }
        else:
            written = _write_custom_patch_key(custom, "translator/enable_user_dict", False)
            schemas[schema_id] = {
                "action": "disable",
                "written": written,
                "custom_path": str(custom),
                "custom_exists": custom.is_file(),
            }

    result: dict[str, Any] = {
        "action": "set_learning",
        "on": bool(on),
        "schemas": schemas,
        "deploy": None,
        "clean": None,
    }
    if deploy:
        result["deploy"] = _deploy_dict()
        result["clean"] = bool(result["deploy"]["clean"])
    result["state"] = learning_state(user_dir)
    return result


def sync_user_data(
    *,
    timeout: float = 180.0,
    user_dir: str | os.PathLike[str] | None = None,
) -> dict[str, Any]:
    """Run ``WeaselDeployer.exe /sync`` (serialized, bounded by ``timeout``)."""
    with _DEPLOYER_LOCK:
        deployer = paths.weasel_deployer_exe(paths.weasel_root())
        result: dict[str, Any] = {
            "action": "sync_user_data",
            "deployer": str(deployer) if deployer else None,
            "ran": False,
            "exit_code": None,
            "timed_out": False,
            "busy": False,
            "stdout": "",
            "stderr": "",
            "note": "",
            "clean": False,
        }
        if not deployer or not Path(deployer).is_file():
            result["note"] = "WeaselDeployer.exe could not be resolved"
            return result

        try:
            busy = _deploy.is_deployer_running()
        except Exception:  # pragma: no cover - defensive
            busy = False
        if busy:
            result["busy"] = True
            result["note"] = "另一个部署器正在运行；未启动同步。"
            return result

        try:
            completed = subprocess.run(
                [str(deployer), "/sync"],
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=timeout,
                cwd=str(Path(deployer).parent),
                **winproc.no_window_kwargs(),
            )
        except subprocess.TimeoutExpired as exc:
            result["ran"] = True
            result["timed_out"] = True
            result["stdout"] = (exc.stdout or "") if isinstance(exc.stdout, str) else ""
            result["stderr"] = (exc.stderr or "") if isinstance(exc.stderr, str) else ""
            result["note"] = f"/sync timed out after {timeout:g}s"
            return result
        except OSError as exc:
            result["note"] = f"failed to launch /sync: {exc}"
            return result

        result["ran"] = True
        result["exit_code"] = completed.returncode
        result["stdout"] = completed.stdout or ""
        result["stderr"] = completed.stderr or ""
        result["busy"] = completed.returncode == 1
        result["clean"] = completed.returncode == 0 and not result["stderr"].strip()
        if result["busy"]:
            result["note"] = "exit code 1: another deployer is running (busy)"
        elif result["clean"]:
            result["note"] = "用户数据已同步（退出码 0，stderr 为空）。"
        else:
            result["note"] = (
                f"/sync exited with code {completed.returncode}; stderr: "
                f"{result['stderr'].strip() or '（空）'}"
            )
        return result


