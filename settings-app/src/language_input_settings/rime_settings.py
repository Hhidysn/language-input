def _schema_switch_defs(
    schema_id: str, user_dir: str | os.PathLike[str] | None = None
) -> dict[str, dict[str, Any]]:
    """Switch name -> ``{default, states, kind}`` from the compiled schema."""
    document = _load_yaml(_compiled_schema_path(schema_id, user_dir))
    defs: dict[str, dict[str, Any]] = {}
    if not isinstance(document, dict):
        return defs
    switches = document.get("switches")
    if not isinstance(switches, list):
        return defs

    for item in switches:
        if not isinstance(item, dict):
            continue
        name = item.get("name")
        reset = item.get("reset")
        states = item.get("states") or []
        if isinstance(name, str) and name.startswith("language_input_"):
            default = bool(reset) if isinstance(reset, (bool, int)) else None
            defs[name] = {"default": default, "states": states, "kind": "bool"}
            continue
        options = item.get("options")
        if isinstance(options, (list, tuple)) and any(
            isinstance(option, str) and option.startswith("language_input_")
            for option in options
        ):
            for index, option in enumerate(options):
                if not isinstance(option, str):
                    continue
                default = None
                if isinstance(reset, int) and 0 <= reset < len(options):
                    default = index == reset
                defs[option] = {
                    "default": default,
                    "states": states,
                    "kind": "language",
                    "group": [str(o) for o in options],
                }
    return defs


def _combined_switch_defs(
    user_dir: str | os.PathLike[str] | None = None,
) -> dict[str, dict[str, Any]]:
    combined: dict[str, dict[str, Any]] = {}
    for schema_id in LANGUAGE_SCHEMAS:
        for name, definition in _schema_switch_defs(schema_id, user_dir).items():
            combined.setdefault(name, definition)
    return combined


def language_input_switches(
    user_dir: str | os.PathLike[str] | None = None,
) -> list[dict[str, Any]]:
    """Describe every Language Input switch with label, value and schema default.

    ``default`` is the explicit ``reset`` value from the compiled schema (the
    UI renders it as 「默认」); it is ``None`` once the resets have been
    neutralized, in which case the saved value is authoritative.
    """
    defs = _combined_switch_defs(user_dir)
    saved = yaml_io.read_user_yaml_options(_user_yaml_path(user_dir))
    rows: list[dict[str, Any]] = []
    for name in SWITCH_ORDER:
        definition = defs.get(name, {})
        default = definition.get("default")
        saved_value = saved.get(name)
        if saved_value is not None:
            value = saved_value
        elif default is not None:
            value = default
        else:
            value = False
        if default is None:
            default_label = "默认：未知（未编译）"
        else:
            default_label = "默认：" + ("开" if default else "关")
        rows.append(
            {
                "name": name,
                "label": SWITCH_LABELS.get(name, name),
                "group": "language" if name in LANGUAGE_GROUP else None,
                "kind": definition.get("kind", "bool"),
                "states": definition.get("states", []),
                "value": bool(value),
                "saved": saved_value,
                "default": default,
                "default_label": default_label,
            }
        )
    return rows


def read_switches(
    user_dir: str | os.PathLike[str] | None = None,
) -> dict[str, bool]:
    """Saved ``var/option/*`` booleans from ``user.yaml`` (read-only)."""
    return yaml_io.read_user_yaml_options(_user_yaml_path(user_dir))


def set_switches(
    changes: dict[str, bool],
    *,
    deploy: bool = True,
    user_dir: str | os.PathLike[str] | None = None,
) -> dict[str, Any]:
    """Atomically set one or more ``var/option/*`` switches, then redeploy.

    The three language options are mutually exclusive: turning any one on
    clears the other two.

    The ``user.yaml`` write is a full stop → wait → atomic-write → restart
    transaction (:func:`server.server_stopped`), because the running server
    holds ``user.yaml`` with ``auto_save`` and rewrites the whole file.  A
    no-op request (all saved values already match) does not touch the server.
    """
    path = _user_yaml_path(user_dir)
    normalized: dict[str, bool] = {}
    for name, value in changes.items():
        if name not in SWITCH_ORDER:
            raise RimeSettingsError(f"unknown switch: {name}")
        normalized[name] = bool(value)

    if any(normalized.get(name) for name in LANGUAGE_GROUP):
        for name in LANGUAGE_GROUP:
            normalized.setdefault(name, False)

    # Only the options whose *saved* value actually differs need a write (this
    # also avoids taking the stop/start transaction for a no-op).
    saved = yaml_io.read_user_yaml_options(path)
    pending = {
        name: value
        for name, value in normalized.items()
        if saved.get(name) != value
    }

    result: dict[str, Any] = {
        "action": "set_switches",
        "requested": normalized,
        "changed": [],
        "user_yaml": str(path),
        "options_after": read_switches(user_dir),
        "server": None,
        "deploy": None,
        "clean": None,
    }
    if not pending:
        return result

    # B2: WeaselServer holds user.yaml with auto_save and rewrites the whole
    # file, so the write must happen with the server stopped (design §5.6).
    # ``server_stopped`` holds the exclusive mutex across the transaction and
    # restarts the server with its previous environment afterwards.
    with _server.server_stopped() as tx:
        changed_keys: list[str] = []
        for name, value in pending.items():
            if yaml_io.set_user_yaml_option(path, name, value):
                changed_keys.append(name)
        result["changed"] = changed_keys

    # ``server_stopped`` restarts the server on exit, so read its final state
    # *after* the ``with`` block (the yielded dict is mutated by the restart).
    result["server"] = {
        "was_running": tx["was_running"],
        "stopped": tx["stopped"],
        "model_host_exited": tx["model_host_exited"],
        "restarted": tx["started"],
        "pids": tx["pids"],
        "restart_error": tx["start_error"],
    }

    result["options_after"] = read_switches(user_dir)
    if deploy and result["changed"]:
        result["deploy"] = _deploy_dict()
        result["clean"] = bool(result["deploy"]["clean"])
        result["options_after"] = read_switches(user_dir)
    return result


def set_switch(
    name: str,
    on: bool,
    *,
    deploy: bool = True,
    user_dir: str | os.PathLike[str] | None = None,
) -> dict[str, Any]:
    """Set a single switch; the language options behave as a radio group."""
    return set_switches({name: on}, deploy=deploy, user_dir=user_dir)


