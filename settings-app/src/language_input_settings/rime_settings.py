def _humanize_keys(accept: str) -> str:
    if not accept:
        return ""
    parts = [_KEY_NAMES.get(part.strip().lower(), part.strip()) for part in accept.split("+")]
    return "+".join(parts)


def _binding_effect(binding: dict[str, Any]) -> str:
    if "toggle" in binding:
        target = str(binding["toggle"])
        return _TOGGLE_ACTIONS.get(target, f"切换 {target}")
    if "select" in binding:
        target = str(binding["select"])
        return "切换到下一方案" if target == ".next" else f"选择 {target}"
    if "send" in binding:
        target = str(binding["send"])
        return _SEND_ACTIONS.get(target, f"发送 {target}")
    return "（未识别的动作）"


def _raw_binding(binding: dict[str, Any]) -> str:
    return ", ".join(f"{key}={value}" for key, value in binding.items())


def hotkeys(
    user_dir: str | os.PathLike[str] | None = None,
    weasel_root: str | os.PathLike[str] | None = None,
) -> list[dict[str, Any]]:
    """Read-only, human-readable view of the configured key bindings.

    Prefers the compiled ``<userdir>\\build\\default.yaml`` (the merged result);
    falls back to the installed ``default.yaml``.  Nothing is invented: each row
    carries the raw configured value.
    """
    compiled = _coerce_user_dir(user_dir) / "build" / "default.yaml"
    source: Path | None = compiled if compiled.is_file() else None
    if source is None:
        root = _weasel_root(weasel_root)
        candidate = Path(root) / "data" / "default.yaml" if root else None
        source = candidate if candidate is not None and candidate.is_file() else None
    document = _load_yaml(source) if source is not None else None
    if not isinstance(document, dict):
        return []

    rows: list[dict[str, Any]] = []
    switcher = document.get("switcher")
    if isinstance(switcher, dict):
        for raw in switcher.get("hotkeys") or []:
            text = str(raw)
            rows.append(
                {
                    "group": "方案与选项",
                    "keys": _humanize_keys(text),
                    "action": _SWITCHER_ACTIONS.get(text.lower(), "方案选单热键"),
                    "raw": text,
                }
            )

    binder = document.get("key_binder")
    if isinstance(binder, dict):
        for binding in binder.get("bindings") or []:
            if not isinstance(binding, dict):
                continue
            rows.append(
                {
                    "group": "按键绑定",
                    "keys": _humanize_keys(str(binding.get("accept", ""))),
                    "action": _binding_effect(binding),
                    "raw": _raw_binding(binding),
                }
            )
    return rows


