"""Rime / Weasel settings operations: appearance, switches and memory.

This module implements the three pages that used to be placeholders:

* **Appearance** -- the candidate-window style.  Values are read from the
  *installed* ``<weasel_root>\\data\\weasel.yaml`` (the real key set is
  enumerated, never guessed) and written to the app-owned
  ``<userdir>\\weasel.custom.yaml`` under a **merged** ``patch:`` mapping, so
  the file's existing keys (e.g. ``style/color_scheme``) are preserved.
* **Switches** -- the Language Input F4 switches.  Persisted in
  ``<userdir>\\user.yaml`` as ``var/option/<name>`` (design doc §5.5).  The
  three ``language_input_en/ja/es`` options form a mutually exclusive radio
  group.  ``hotkeys()`` exposes the configured bindings read-only.
* **Memory / dictionary** -- ``translator/enable_user_dict`` patched through
  each schema's ``<schema>.custom.yaml`` (design doc §8), user-dictionary
  presence/size, ``/sync`` and the detached ``/dict`` launcher.

Writing rules (design doc §5.6): UTF-8 **without BOM**, LF newlines, atomic
(temp + ``os.replace``), back up first.  Rime's own exported configuration is
never round-trip-rewritten; the app-owned patch files ``weasel.custom.yaml``
and ``<schema>.custom.yaml`` are edited with a round-trip ruamel document
(like :mod:`schema_patch`), so nested and flat ``patch:`` spellings are both
resolved for reads and writes.  ``user.yaml`` is edited surgically (line-based)
via :mod:`yaml_io`.

Live config writes (``user.yaml``) go through
:func:`server.server_stopped`: the server holds ``user.yaml`` with
``auto_save`` and rewrites the whole file, so every switch edit is a
stop → wait → atomic-write → restart transaction (design §5.6 / B2).

``/deploy`` returns exit code ``0`` even for invalid YAML: success is judged by
an empty stderr **and** by re-reading the resulting state.
"""

