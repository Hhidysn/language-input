def _require_yaml():
    if _YAML is None:  # pragma: no cover - dependency missing
        raise RimeSettingsError("ruamel.yaml is required for Rime settings")
    return _YAML


def _require_map():
    if _CommentedMap is None:  # pragma: no cover - dependency missing
        raise RimeSettingsError("ruamel.yaml is required for Rime settings")
    return _CommentedMap


def _load_yaml(path: Path | None) -> Any:
    """Parse a Rime config file read-only (never used to rewrite it)."""
    if path is None or not Path(path).is_file():
        return None
    yaml = _require_yaml()
    try:
        text = Path(path).read_text(encoding="utf-8-sig")
        # Rime tolerates tabs (e.g. ``max_width: 0\t#comment`` in weasel.yaml)
        # but strict YAML does not; tabs are only ever whitespace here.
        text = text.replace("\t", " ")
        return yaml(typ="safe").load(text)
    except RimeSettingsError:
        raise
    except Exception as exc:  # noqa: BLE001 - malformed input
        raise RimeSettingsError(f"cannot parse {path}: {exc}") from exc


def _flatten(mapping: Any, prefix: str = "") -> dict[str, Any]:
    """Flatten nested mappings into slash-separated keys (leaves only)."""
    out: dict[str, Any] = {}
    if not isinstance(mapping, dict):
        return out
    for key, value in mapping.items():
        path = f"{prefix}/{key}" if prefix else str(key)
        if isinstance(value, dict) and value:
            out.update(_flatten(value, path))
        else:
            out[path] = value
    return out


# --- shared deploy helper ---------------------------------------------------

def _deploy_dict(timeout: float = 120.0) -> dict[str, Any]:
    """Run ``/deploy`` and report the result.

    ``/deploy`` returns 0 even for invalid YAML; ``clean`` therefore also
    requires an empty stderr (design doc §5.6).
    """
    with _DEPLOYER_LOCK:
        deployer = paths.weasel_deployer_exe(paths.weasel_root())
        result = _deploy.run_deploy(deployer, timeout=timeout)
    return {
        "ran": result.ran,
        "exit_code": result.exit_code,
        "timed_out": result.timed_out,
        "busy": result.busy,
        "stderr": result.stderr,
        "note": result.note,
        "clean": bool(result.ran)
        and result.exit_code == 0
        and not (result.stderr or "").strip(),
    }


def run_deploy(timeout: float = 120.0) -> dict[str, Any]:
    """Public wrapper: run ``/deploy`` and report the checked result.

    ``clean`` requires the process to have run, exit code ``0`` **and** an
    empty stderr (design doc §5.6: exit 0 does not prove the config was valid).
    """
    return _deploy_dict(timeout=timeout)


