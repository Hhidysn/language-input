def open_dict_manager(
    *,
    user_dir: str | os.PathLike[str] | None = None,
) -> dict[str, Any]:
    """Launch ``WeaselDeployer.exe /dict`` detached (non-blocking).

    The dialog is modal to the deployer process, not to this app, and the call
    returns immediately.
    """
    deployer = paths.weasel_deployer_exe(paths.weasel_root())
    result: dict[str, Any] = {
        "action": "open_dict_manager",
        "deployer": str(deployer) if deployer else None,
        "launched": False,
        "pid": None,
        "note": dict_manager_note(),
    }
    if not deployer or not Path(deployer).is_file():
        result["note"] = "找不到 WeaselDeployer.exe，无法打开词典管理。"
        return result
    try:
        process = subprocess.Popen(
            [str(deployer), "/dict"],
            cwd=str(Path(deployer).parent),
            close_fds=True,
            **winproc.no_window_kwargs(detached=True),
        )
    except OSError as exc:
        result["note"] = f"无法启动词典管理：{exc}"
        return result
    result["launched"] = True
    result["pid"] = process.pid
    return result
