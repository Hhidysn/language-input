def _resolve_requested(values: dict[str, Any]) -> dict[str, dict[str, Any]]:
    resolved: dict[str, dict[str, Any]] = {}
    for wanted, actual in REQUESTED_STYLE_KEYS.items():
        if actual in values:
            resolved[wanted] = {
                "exists": True,
                "value": values[actual],
                "actual_path": actual,
            }
        else:
            resolved[wanted] = {
                "exists": False,
                "value": None,
                "actual_path": None,
            }
            if wanted != actual:
                resolved[wanted]["hint"] = f"实际键为 {actual}"
    return resolved


def read_weasel_style(
    weasel_root: str | os.PathLike[str] | None = None,
) -> dict[str, Any]:
    """Read the **installed** ``weasel.yaml`` and enumerate its real style keys.

    Returns a flattened ``style`` mapping (``style/layout/corner_radius`` etc.),
    the sorted list of every real key, the requested-key resolution and the
    available ``preset_color_schemes`` names.  Never raises on a missing file.
    """
    path = _weasel_yaml_path(weasel_root)
    document = _load_yaml(path) if path is not None else None
    style = document.get("style") if isinstance(document, dict) else None
    flat = _flatten(style, "style")
    presets = document.get("preset_color_schemes") if isinstance(document, dict) else None
    return {
        "weasel_root": str(_weasel_root(weasel_root)) if _weasel_root(weasel_root) else None,
        "weasel_yaml": str(path) if path is not None else None,
        "exists": isinstance(document, dict),
        "style": flat,
        "available_keys": sorted(flat),
        "requested": _resolve_requested(flat),
        "preset_color_schemes": sorted(str(k) for k in presets)
        if isinstance(presets, dict)
        else [],
    }


def available_color_schemes(
    weasel_root: str | os.PathLike[str] | None = None,
    user_dir: str | os.PathLike[str] | None = None,
) -> list[str]:
    """Colour-scheme names derived from the install's ``preset_color_schemes``.

    The currently selected scheme is appended if the install no longer ships it,
    so the UI can always show the effective value.
    """
    path = _weasel_yaml_path(weasel_root)
    document = _load_yaml(path) if path is not None else None
    names: list[str] = []
    if isinstance(document, dict):
        presets = document.get("preset_color_schemes")
        if isinstance(presets, dict):
            names = sorted(str(k) for k in presets)
    patch = weasel_custom_patch(user_dir)
    effective = patch.get("style/color_scheme")
    if effective and str(effective) not in names:
        names.append(str(effective))
    return names


def weasel_custom_patch(
    user_dir: str | os.PathLike[str] | None = None,
) -> dict[str, Any]:
    """Flattened ``patch:`` mapping of ``weasel.custom.yaml`` (read-only)."""
    path = _custom_weasel_path(user_dir)
    document = _load_yaml(path)
    patch = document.get("patch") if isinstance(document, dict) else None
    return _flatten(patch, "")


def current_style(
    user_dir: str | os.PathLike[str] | None = None,
    weasel_root: str | os.PathLike[str] | None = None,
) -> dict[str, Any]:
    """Effective style = installed defaults overlaid by ``weasel.custom.yaml``."""
    base = read_weasel_style(weasel_root)
    defaults: dict[str, Any] = dict(base["style"])
    patch = weasel_custom_patch(user_dir)
    values = dict(defaults)
    values.update(patch)
    custom = _custom_weasel_path(user_dir)
    return {
        "weasel_yaml": base["weasel_yaml"],
        "custom_path": str(custom),
        "custom_exists": custom.is_file(),
        "defaults": defaults,
        "patch": patch,
        "values": values,
        "requested": _resolve_requested(values),
    }


# -- weasel.custom.yaml editing ----------------------------------------------
#
# ``weasel.custom.yaml`` is a plain Rime ``patch:`` file.  A patch key may be
# written either flat (``"style/font_point": 15``) or nested::
#
#     patch:
#       style:
#         font_point: 15
#
# librime treats the two spellings identically (``/`` is a path separator), so
# both reads and writes must resolve the *flattened* path.  A ruamel
# round-trip document is used (like :mod:`schema_patch`) so comments and the
# unrelated structure survive.  This replaces the old flat-only line editor,
# which appended a duplicate flat key for a nested file and silently did
# nothing when asked to remove a nested key (S6).


def _find_leaf(mapping: dict, parts: list[str]):
    """Return ``(parent_mapping, leaf_key)`` for slash-path ``parts`` or ``None``."""
    joined = "/".join(parts)
    if joined in mapping and not isinstance(mapping[joined], dict):
        return mapping, joined
    if len(parts) == 1:
        return None
    child = mapping.get(parts[0])
    if isinstance(child, dict):
        return _find_leaf(child, parts[1:])
    return None


def _prune_empty_maps(mapping: dict) -> None:
    """Recursively drop nested mappings that became empty (keeps the root)."""
    for key in list(mapping.keys()):
        value = mapping[key]
        if isinstance(value, dict):
            _prune_empty_maps(value)
            if not value:
                del mapping[key]


def _edit_weasel_patch(text: str, changes: dict[str, Any]) -> str:
    """Return ``text`` with ``changes`` merged into the ``patch:`` mapping.

    ``changes`` keys are slash paths (``style/font_point``); they are resolved
    against the flattened patch, so the flat and nested spellings are
    equivalent.  A ``None`` value removes the key (and prunes a parent mapping
    that becomes empty).  A ruamel round-trip document preserves comments and
    the rest of the file.
    """
    yaml = _require_yaml()()
    yaml.preserve_quotes = True
    yaml.allow_unicode = True
    yaml.default_flow_style = False
    yaml.indent(mapping=2, sequence=4, offset=2)
    try:
        document = yaml.load(text) if text.strip() else None
    except Exception as exc:  # noqa: BLE001 - malformed user file
        raise RimeSettingsError(f"cannot parse weasel.custom.yaml: {exc}") from exc
    map_class = _require_map()
    if document is None:
        document = map_class()
    if not isinstance(document, dict):
        raise RimeSettingsError("weasel.custom.yaml is not a YAML mapping")
    patch = document.get("patch")
    if not isinstance(patch, dict):
        patch = map_class()
        document["patch"] = patch

    for key, value in changes.items():
        parts = [part for part in str(key).split("/") if part]
        if not parts:
            continue
        found = _find_leaf(patch, parts)
        if value is None:
            if found is not None:
                parent, leaf = found
                del parent[leaf]
                _prune_empty_maps(patch)
            continue
        if found is not None:
            parent, leaf = found
            parent[leaf] = value
            continue
        # Create the nested mapping chain for a key that does not exist yet.
        target = patch
        for part in parts[:-1]:
            child = target.get(part)
            if not isinstance(child, dict):
                child = map_class()
                target[part] = child
            target = child
        target[parts[-1]] = value

    buffer = StringIO()
    yaml.dump(document, buffer)
    return buffer.getvalue()


def _normalize_style_key(key: str) -> str:
    normalized = str(key).strip()
    if not normalized.startswith("style/"):
        normalized = "style/" + normalized
    return REQUESTED_STYLE_KEYS.get(normalized, normalized)


def _coerce_style_value(value: Any) -> Any:
    if value is None or isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return value
    text = str(value).strip()
    lowered = text.lower()
    if lowered in ("true", "yes", "on"):
        return True
    if lowered in ("false", "no", "off"):
        return False
    if re.fullmatch(r"-?\d+", text):
        return int(text)
    if re.fullmatch(r"-?\d+\.\d+", text):
        return float(text)
    return text


def apply_style(
    patch: dict[str, Any],
    *,
    deploy: bool = True,
    user_dir: str | os.PathLike[str] | None = None,
    weasel_root: str | os.PathLike[str] | None = None,
) -> dict[str, Any]:
    """Merge ``patch`` into ``weasel.custom.yaml`` and (optionally) redeploy.

    Keys may be slash paths (``style/font_point``), bare names
    (``font_point``) or the design-doc alias ``style/corner_radius``.  A value
    of ``None`` removes the key (used to restore the original state).
    """
    changes: dict[str, Any] = {}
    for key, value in patch.items():
        changes[_normalize_style_key(key)] = _coerce_style_value(value)

    path = _custom_weasel_path(user_dir)
    original = path.read_text(encoding="utf-8-sig") if path.is_file() else ""
    updated = _edit_weasel_patch(original, changes)
    changed = updated != original
    backup: Path | None = None
    if changed:
        backup = yaml_io.backup_file(path)
        yaml_io.atomic_write_text(path, updated)

    result: dict[str, Any] = {
        "action": "apply_style",
        "custom_path": str(path),
        "changes": {k: v for k, v in changes.items()},
        "changed": changed,
        "backup_path": str(backup) if backup else None,
        "custom_exists": path.is_file(),
        "applied": {},
        "deploy": None,
        "clean": None,
    }
    if changed:
        result["applied"] = current_style(user_dir, weasel_root)["values"]

    if deploy and changed:
        result["deploy"] = _deploy_dict()
        result["clean"] = bool(result["deploy"]["clean"])
        # Re-read the state after deploying (exit code 0 is not proof).
        result["effective"] = current_style(user_dir, weasel_root)["values"]
    return result


